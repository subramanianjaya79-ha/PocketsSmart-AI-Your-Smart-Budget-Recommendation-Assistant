"""Prompt orchestration + Gemini calls + fallbacks for PocketSmart AI."""
import json, os, re
from urllib.parse import quote_plus
from dotenv import load_dotenv

load_dotenv()
MODEL_NAME = os.getenv("GEMINI_MODEL", "gemini-2.5-flash")
_API_KEY = os.getenv("GEMINI_API_KEY")

try:
    import google.generativeai as genai
    if _API_KEY:
        genai.configure(api_key=_API_KEY)
except ImportError:  # allows running UI without the SDK
    genai = None

SEARCH_URLS = {
    "amazon": "https://www.amazon.in/s?k=", "flipkart": "https://www.flipkart.com/search?q=",
    "ikea": "https://www.ikea.com/in/en/search/?q=", "swiggy": "https://www.swiggy.com/search?query=",
    "zomato": "https://www.zomato.com/search?q=", "oyo": "https://www.oyorooms.com/search?query=",
}

SCHEMA = """Respond ONLY with JSON (no markdown) in this exact shape:
{"summary": "short overview", "total_estimate": 0,
 "items": [{"category": "", "name": "", "platform": "", "price": 0, "reason": ""}],
 "tips": ["..."]}
Prices are numbers in INR. total_estimate must NOT exceed the budget."""


def product_link(platform: str, name: str) -> str:
    base = SEARCH_URLS.get((platform or "").lower().strip())
    return base + quote_plus(name) if base else "https://www.google.com/search?q=" + quote_plus(f"{name} {platform}")


def _parse(text: str) -> dict:
    text = re.sub(r"^```(?:json)?|```$", "", text.strip(), flags=re.M).strip()
    return json.loads(text)


def _finalize(data: dict, budget: float) -> dict:
    items = data.get("items") or []
    if not items:
        raise ValueError("empty result")
    for it in items:
        it["price"] = float(it.get("price") or 0)
        it["link"] = product_link(it.get("platform", ""), it.get("name", ""))
    total = sum(i["price"] for i in items)
    data.update(items=items, total_estimate=total, budget=budget,
                within_budget=total <= budget, tips=data.get("tips") or [])
    data.setdefault("summary", "")
    return data


def _call(prompt: str, image=None) -> dict:
    if genai is None or not _API_KEY:
        raise RuntimeError("Gemini not configured")
    model = genai.GenerativeModel(MODEL_NAME, generation_config={"response_mime_type": "application/json"})
    parts = [prompt] + ([image] if image is not None else [])
    return _parse(model.generate_content(parts).text)


def _fallback(kind: str, budget: float) -> dict:
    """Proportional default suggestions when the AI is unavailable or returns nothing."""
    plans = {
        "home": [("Lighting", "LED ceiling light", "IKEA", .25), ("Furniture", "Dining table set", "Amazon", .45),
                 ("Cooling", "BLDC ceiling fan", "Flipkart", .20), ("Decor", "Wall art & cushions", "IKEA", .10)],
        "party": [("Catering", "Party food platters", "Zomato", .50), ("Decoration", "Balloon & light decor kit", "Amazon", .20),
                  ("Entertainment", "Speaker & games", "Flipkart", .15), ("Venue/Stay", "Nearby room/hall booking", "OYO", .15)],
        "jewelry": [("Necklace", "Statement necklace", "Amazon", .50), ("Earrings", "Matching earrings", "Flipkart", .30),
                    ("Bangles", "Bangle set", "Amazon", .20)],
    }[kind]
    items = [{"category": c, "name": n, "platform": p, "price": round(budget * w), "reason": "Default budget-share suggestion."}
             for c, n, p, w in plans]
    return _finalize({"summary": "AI was unavailable, so default suggestions were generated by budget share.",
                      "items": items, "tips": ["Add your Gemini API key in .env for personalised results."]}, budget)


def _run(kind: str, prompt: str, budget: float, image=None) -> dict:
    try:
        return _finalize(_call(prompt + "\n\n" + SCHEMA, image), budget)
    except Exception as e:
        print(f"[gemini] fallback used: {e}")
        return _fallback(kind, budget)


def home_recommendations(budget, style, rooms, quantities):
    prompt = (f"You are a home interior budget planner for India. Budget: INR {budget}. Style: {style}. "
              f"Rooms: {', '.join(rooms) or 'any'}. Quantities needed: {json.dumps(quantities)}. "
              "Recommend cost-effective products balancing function, style and price from IKEA, Amazon, Flipkart.")
    return _run("home", prompt, budget)


def party_recommendations(budget, guests, event_type, venue, city=""):
    per_head = round(budget / max(guests, 1))
    prompt = (f"You are a party budget planner. Total budget INR {budget}, {guests} guests (~INR {per_head}/head), "
              f"event: {event_type}, venue: {venue}, city: {city}. Allocate the budget across catering, decoration, "
              "entertainment (and stay if guests travel), tailored to the event type. Use Swiggy, Zomato, OYO, Amazon.")
    return _run("party", prompt, budget)


def jewelry_recommendations(budget, occasion, style, image=None):
    prompt = (f"You are a jewelry stylist. Budget INR {budget}, occasion: {occasion}, style: {style}. "
              + ("An outfit image is attached: match colours and aesthetics to it. " if image is not None else "")
              + "Suggest matching pieces from Amazon and Flipkart.")
    return _run("jewelry", prompt, budget, image)
